import * as fs from 'node:fs';
import * as path from 'node:path';
import * as vscode from 'vscode';
import { KiCadExportService } from '../../src/cli/exportCommands';
import { workspace } from './vscodeMock';

function fileUri(file: string): vscode.Uri {
  // The lightweight VS Code unit stub does not model Uri.scheme.
  return Object.assign(vscode.Uri.file(file), { scheme: 'file' });
}

describe('KiCadExportService native inner-copper plot', () => {
  let directory: string;

  beforeEach(() => {
    directory = fs.mkdtempSync(
      path.join(process.cwd(), '.tmp-studio-native-copper-')
    );
    workspace.isTrusted = true;
  });

  afterEach(() => {
    workspace.isTrusted = true;
    fs.rmSync(directory, { recursive: true, force: true });
  });

  function createService(version = '10.0.8') {
    let cliSource: string | undefined;
    let outputFile: string | undefined;
    const runner = {
      run: jest.fn(
        async ({ command, cwd }: { command: string[]; cwd: string }) => {
          cliSource = command.at(-1);
          outputFile = command[command.indexOf('--output') + 1];
          expect(path.dirname(cliSource!)).toBe(cwd);
          expect(path.dirname(outputFile!)).toBe(cwd);
          expect(cliSource).not.toContain(directory);
          expect(fs.readFileSync(cliSource!, 'utf8')).toContain('(kicad_pcb');
          fs.writeFileSync(
            outputFile!,
            '<svg xmlns="http://www.w3.org/2000/svg"><desc>Image generated by PCBNEW</desc><circle r="1"/></svg>',
            'utf8'
          );
          // KiCad sometimes writes project-local metadata beside its input;
          // that must be contained in the task-owned temporary snapshot.
          fs.writeFileSync(path.join(cwd, 'source.kicad_prl'), '{}', 'utf8');
          return { stdout: '', stderr: '', exitCode: 0, durationMs: 1 };
        }
      )
    };
    const detector = {
      detect: jest.fn().mockResolvedValue({ version, path: 'kicad-cli' })
    };
    const logger = {
      info: jest.fn(),
      warn: jest.fn(),
      error: jest.fn(),
      debug: jest.fn()
    };
    const service = new KiCadExportService(
      runner as never,
      detector as never,
      {} as never,
      {} as never,
      {} as never,
      logger as never
    );
    return {
      service,
      runner,
      detector,
      getSnapshot: () => cliSource,
      getOutput: () => outputFile
    };
  }

  it('runs one whitelisted inner copper plot on a temp snapshot without editing the original', async () => {
    const board = path.join(directory, 'original.kicad_pcb');
    const data = '(kicad_pcb (layers (1 "In1.Cu" signal) (2 "In2.Cu" signal)))';
    fs.writeFileSync(board, data, 'utf8');
    const { service, runner, getSnapshot, getOutput } = createService();
    const svg = await service.renderViewerNativeInnerCopperLayer(
      fileUri(board),
      'In2.Cu'
    );
    expect(svg).toContain('Image generated by PCBNEW');
    expect(runner.run).toHaveBeenCalledTimes(1);
    expect(runner.run).toHaveBeenCalledWith(
      expect.objectContaining({
        command: expect.arrayContaining([
          'pcb',
          'export',
          'svg',
          '--layers',
          'In2.Cu',
          '--mode-single',
          '--drill-shape-opt',
          '2'
        ])
      })
    );
    expect(fs.readFileSync(board, 'utf8')).toBe(data);
    expect(getSnapshot()).toBeDefined();
    expect(fs.existsSync(getSnapshot()!)).toBe(false);
    expect(fs.existsSync(getOutput()!)).toBe(false);
    expect(fs.existsSync(path.join(directory, 'original.kicad_prl'))).toBe(
      false
    );
  });

  it.each(['F.Cu', 'B.Cu'])(
    'plots only real %s copper through the existing disposable KiCad CLI path',
    async (layer) => {
      const board = path.join(directory, 'outer-board.kicad_pcb');
      const source =
        '(kicad_pcb (layers (0 "F.Cu" signal) (31 "B.Cu" signal)))';
      fs.writeFileSync(board, source, 'utf8');
      const { service, runner, getSnapshot } = createService();
      const svg = await service.renderViewerNativeInnerCopperLayer(
        fileUri(board),
        layer
      );
      expect(svg).toContain('Image generated by PCBNEW');
      expect(runner.run).toHaveBeenCalledWith(
        expect.objectContaining({
          command: expect.arrayContaining(['--layers', layer, '--mode-single'])
        })
      );
      expect(fs.readFileSync(board, 'utf8')).toBe(source);
      expect(fs.existsSync(getSnapshot()!)).toBe(false);
      expect(fs.existsSync(path.join(directory, 'outer-board.kicad_prl'))).toBe(
        false
      );
    }
  );

  it('plots only the authorized bounded PCB subset instead of the full source', async () => {
    const original = path.join(directory, 'full.kicad_pcb');
    fs.writeFileSync(
      original,
      '(kicad_pcb (footprint "FULL_SECRET_GEOMETRY"))',
      'utf8'
    );
    const bounded = '(kicad_pcb (footprint "BOUNDED_PAD_ONLY"))';
    const { service, runner, getSnapshot } = createService();
    const svg = await service.renderViewerNativeInnerCopperLayer(
      fileUri(original),
      'In2.Cu',
      bounded
    );
    expect(svg).toContain('Image generated by PCBNEW');
    expect(runner.run).toHaveBeenCalledTimes(1);
    expect(getSnapshot()).toBeDefined();
    expect(fs.existsSync(getSnapshot()!)).toBe(false);
    expect(fs.readFileSync(original, 'utf8')).toContain('FULL_SECRET_GEOMETRY');

    const denied = createService();
    expect(
      await denied.service.renderViewerNativeInnerCopperLayer(
        fileUri(original),
        'In2.Cu',
        '(not-a-pcb)'
      )
    ).toBeUndefined();
    expect(
      await denied.service.renderViewerNativeInnerCopperLayer(
        fileUri(original),
        'In2.Cu',
        '(kicad_pcb' + ' '.repeat(4 * 1024 * 1024)
      )
    ).toBeUndefined();
    expect(denied.runner.run).not.toHaveBeenCalled();
  });

  it('rejects forged layer values and untrusted workspaces without running CLI', async () => {
    const board = path.join(directory, 'original.kicad_pcb');
    fs.writeFileSync(board, '(kicad_pcb)', 'utf8');
    const { service, runner, detector } = createService();
    const resource = fileUri(board);
    for (const layer of [
      'In0.Cu',
      'In31.Cu',
      'In2.Cu,--output',
      '../In2.Cu',
      'In2.Cu\n--output'
    ]) {
      expect(
        await service.renderViewerNativeInnerCopperLayer(resource, layer)
      ).toBeUndefined();
    }
    workspace.isTrusted = false;
    expect(
      await service.renderViewerNativeInnerCopperLayer(resource, 'In2.Cu')
    ).toBeUndefined();
    expect(detector.detect).not.toHaveBeenCalled();
    expect(runner.run).not.toHaveBeenCalled();
  });

  it('rejects unsupported KiCad versions and over-budget source inputs', async () => {
    const board = path.join(directory, 'original.kicad_pcb');
    fs.writeFileSync(board, '(kicad_pcb)', 'utf8');
    const previous = createService('8.0.9');
    expect(
      await previous.service.renderViewerNativeInnerCopperLayer(
        fileUri(board),
        'In1.Cu'
      )
    ).toBeUndefined();
    expect(previous.runner.run).not.toHaveBeenCalled();

    fs.truncateSync(board, 80 * 1024 * 1024 + 1);
    const large = createService();
    expect(
      await large.service.renderViewerNativeInnerCopperLayer(
        fileUri(board),
        'In1.Cu'
      )
    ).toBeUndefined();
    expect(large.detector.detect).not.toHaveBeenCalled();
    expect(large.runner.run).not.toHaveBeenCalled();
  });
});
